import type { LocalizedText } from '@/types/common.types';

/**
 * Единая точка разрешения пользовательского текста.
 *
 * В v1 `LocalizedText` — обычная строка, и функция является тождеством.
 * Её назначение — шов: весь `label` и narrative проходят через неё, поэтому
 * добавление локализации позже сводится к расширению типа и правке этой
 * функции, а не к массовому рефакторингу call-site'ов.
 *
 * Разрешение выполняется один раз в момент создания log event: в лог
 * попадают уже готовые строки, которые не меняются задним числом.
 */
export function resolveText(text: LocalizedText): string {
  return text;
}
